CREATE PROCEDURE SP_VIENCHUC_KHENTHUONG(
    IN p_MAVIENCHUC CHAR(10)
)
BEGIN
    SELECT
        htkt.TENHINHTHUCKHENTHUONG AS HINHTHUC_KHENTHUONG,
        dkt.NAMNHANKHENTHUONG AS NAM,
        dkt.SOQUYETDINHKHENTHUONG,
        dkt.NGUOIKYQUYETDINHKHENTHUONG
    FROM DUOC_KHENTHUONG dkt
    JOIN HINHTHUCKHENTHUONG htkt
        ON dkt.MAHINHTHUCKHENTHUONG = htkt.MAHINHTHUCKHENTHUONG
    WHERE dkt.MAVIENCHUC = p_MAVIENCHUC
    ORDER BY dkt.NAMNHANKHENTHUONG DESC;
END $$

DELIMITER ;


DELIMITER $$

CREATE PROCEDURE SP_VIENCHUC_KYLUAT(
    IN p_MAVIENCHUC CHAR(10)
)
BEGIN
    SELECT
        htkl.TENHINHTHUCKYLUAT AS HINHTHUC_KYLUAT,
        bkl.NAMBIKYLUAT AS NAM,
        bkl.SOQUYETDINHKYLUAT,
        bkl.NGUOIKYQUYETDINHKYLUAT
    FROM BI_KYLUAT bkl
    JOIN HINHTHUCKYLUAT htkl
        ON bkl.MAHINHTHUCKYLUAT = htkl.MAHINHTHUCKYLUAT
    WHERE bkl.MAVIENCHUC = p_MAVIENCHUC
    ORDER BY bkl.NAMBIKYLUAT DESC;
END $$

DELIMITER ;



