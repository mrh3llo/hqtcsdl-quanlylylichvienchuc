CREATE PROCEDURE SP_VIENCHUC_BANG(
    IN p_MAVIENCHUC CHAR(10)
)
BEGIN
    SELECT 
        'CHUYENMON' AS LOAI,
        cm.TENCHUYENMON AS TEN
    FROM CO_TRDCM_CAONHAT ctcm
    JOIN CHUYENMON cm ON ctcm.MACHUYENMON = cm.MACHUYENMON
    WHERE ctcm.MAVIENCHUC = p_MAVIENCHUC

    UNION ALL

    SELECT 
        'NGOAINGU',
        nn.TENNGOAINGU
    FROM CO_TRD_NGOAINGU ctng
    JOIN NGOAINGU nn ON ctng.MANGOAINGU = nn.MANGOAINGU
    WHERE ctng.MAVIENCHUC = p_MAVIENCHUC

    UNION ALL

    SELECT 
        'TINHOC',
        th.CHUNGCHITINHOC
    FROM CO_TRD_TINHOC ctth
    JOIN CHUNGCHITINHOC th ON ctth.MACHUNGCHITINHOC = th.MACHUNGCHITINHOC
    WHERE ctth.MAVIENCHUC = p_MAVIENCHUC;

END $$

DELIMITER ;


