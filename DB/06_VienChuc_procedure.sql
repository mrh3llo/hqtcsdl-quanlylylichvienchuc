CREATE DEFINER='root'@'%' PROCEDURE SP_VIENCHUC_KHENTHUONG()
BEGIN
    DECLARE v_ma CHAR(10);

    SELECT MAVIENCHUC
    INTO v_ma
    FROM USERS
    WHERE MAVIENCHUC = SUBSTRING_INDEX(USER(),'@',1);

    SELECT
        htkt.TENHINHTHUCKHENTHUONG AS HINHTHUC_KHENTHUONG,
        dkt.NAMNHANKHENTHUONG AS NAM,
        dkt.SOQUYETDINHKHENTHUONG,
        dkt.NGUOIKYQUYETDINHKHENTHUONG
    FROM DUOC_KHENTHUONG dkt
    JOIN HINHTHUCKHENTHUONG htkt
        ON dkt.MAHINHTHUCKHENTHUONG = htkt.MAHINHTHUCKHENTHUONG
    WHERE dkt.MAVIENCHUC = v_ma
    ORDER BY dkt.NAMNHANKHENTHUONG DESC;
END $$

