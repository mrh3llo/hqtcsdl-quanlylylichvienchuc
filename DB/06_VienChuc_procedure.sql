CREATE DEFINER='root'@'%' PROCEDURE SP_VIENCHUC_BANG()
BEGIN
    DECLARE v_ma CHAR(10);

    SELECT MAVIENCHUC
    INTO v_ma
    FROM USERS
    WHERE MAVIENCHUC = SUBSTRING_INDEX(USER(),'@',1);

    SELECT
        'CHUYENMON' AS LOAI,
        cm.TENCHUYENMON AS TEN
    FROM CO_TRDCM_CAONHAT ctcm
    JOIN CHUYENMON cm
        ON ctcm.MACHUYENMON = cm.MACHUYENMON
    WHERE ctcm.MAVIENCHUC = v_ma

    UNION ALL

    SELECT
        'NGOAINGU',
        nn.TENNGOAINGU
    FROM CO_TRD_NGOAINGU ctng
    JOIN NGOAINGU nn
        ON ctng.MANGOAINGU = nn.MANGOAINGU
    WHERE ctng.MAVIENCHUC = v_ma

    UNION ALL

    SELECT
        'TINHOC',
        th.CHUNGCHITINHOC
    FROM CO_TRD_TINHOC ctth
    JOIN CHUNGCHITINHOC th
        ON ctth.MACHUNGCHITINHOC = th.MACHUNGCHITINHOC
    WHERE ctth.MAVIENCHUC = v_ma;
END $$

DELIMITER ;


