CREATE PROCEDURE SP_VIENCHUC_LICHSU_CONGTAC(
    IN p_MAVIENCHUC CHAR(10)
)
BEGIN
    SELECT *
    FROM VW_DS_CONGTAC
    WHERE MAVIENCHUC = p_MAVIENCHUC
    ORDER BY 
        CASE 
            WHEN THOIGIANKETTHUCCHUCVU IS NULL THEN 1 
            ELSE 0 
        END DESC,
        THOIGIANGIUCHUCVU DESC;
END $$
