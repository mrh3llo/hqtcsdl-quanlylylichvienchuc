CREATE PROCEDURE SP_CANHAN_KHENTHUONG(
    IN p_MAVIENCHUC CHAR(10)
)
BEGIN
    SELECT
        ht.TENHINHTHUCKHENTHUONG,
        dk.NAMNHANKHENTHUONG,
        dk.SOQUYETDINHKHENTHUONG,
        dk.NGUOIKYQUYETDINHKHENTHUONG
    FROM DUOC_KHENTHUONG dk
    JOIN HINHTHUCKHENTHUONG ht
        ON dk.MAHINHTHUCKHENTHUONG = ht.MAHINHTHUCKHENTHUONG
    WHERE dk.MAVIENCHUC = p_MAVIENCHUC
    ORDER BY dk.NAMNHANKHENTHUONG DESC;
END $$

DELIMITER ;


DELIMITER $$

CREATE PROCEDURE SP_CANHAN_KYLUAT(
    IN p_MAVIENCHUC CHAR(10)
)
BEGIN
    SELECT
        kl.TENHINHTHUCKYLUAT,
        bk.NAMBIKYLUAT,
        bk.SOQUYETDINHKYLUAT,
        bk.NGUOIKYQUYETDINHKYLUAT
    FROM BI_KYLUAT bk
    JOIN HINHTHUCKYLUAT kl
        ON bk.MAHINHTHUCKYLUAT = kl.MAHINHTHUCKYLUAT
    WHERE bk.MAVIENCHUC = p_MAVIENCHUC
    ORDER BY bk.NAMBIKYLUAT DESC;
END $$

