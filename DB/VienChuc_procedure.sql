CREATE PROCEDURE SP_CANHAN_TRINHDO(
    IN p_MAVIENCHUC CHAR(10)
)
BEGIN
    SELECT
        cm.TENCHUYENMON,
        nn.TENNGOAINGU,
        th.CHUNGCHITINHOC
    FROM VIENCHUC vc

    LEFT JOIN CO_TRDCM_CAONHAT ctcm
        ON vc.MAVIENCHUC = ctcm.MAVIENCHUC
    LEFT JOIN CHUYENMON cm
        ON ctcm.MACHUYENMON = cm.MACHUYENMON

    LEFT JOIN CO_TRD_NGOAINGU ctng
        ON vc.MAVIENCHUC = ctng.MAVIENCHUC
    LEFT JOIN NGOAINGU nn
        ON ctng.MANGOAINGU = nn.MANGOAINGU

    LEFT JOIN CO_TRD_TINHOC ctth
        ON vc.MAVIENCHUC = ctth.MAVIENCHUC
    LEFT JOIN CHUNGCHITINHOC th
        ON ctth.MACHUNGCHITINHOC = th.MACHUNGCHITINHOC

    WHERE vc.MAVIENCHUC = p_MAVIENCHUC;
END $$

DELIMITER ;


