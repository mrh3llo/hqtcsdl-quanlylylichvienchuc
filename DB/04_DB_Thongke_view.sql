--   ? gender
CREATE VIEW VW_THONGKE_GIOITINH AS
SELECT
    GIOITINH,
    COUNT(*) AS SOLUONG
FROM VIENCHUC
GROUP BY GIOITINH;


-- ? enthiicity
CREATE VIEW VW_THONGKE_DANTOC AS
SELECT
    dt.TENDANTOC,
    COUNT(*) AS SOLUONG
FROM VIENCHUC vc
JOIN DANTOC dt ON vc.MADANTOC = dt.MADANTOC
GROUP BY dt.TENDANTOC;

-- ?  religion
CREATE VIEW VW_THONGKE_TONGIAO AS
SELECT
    tg.TENTONGIAO,
    COUNT(*) AS SOLUONG
FROM VIENCHUC vc
LEFT JOIN TONGIAO tg ON vc.MATONGIAO = tg.MATONGIAO
GROUP BY tg.TENTONGIAO;


CREATE VIEW VW_THONGKE_DOTUOI AS
SELECT
    CASE
        WHEN TIMESTAMPDIFF(YEAR, NGAYSINH, CURDATE()) < 30 THEN 'Duoi 30'
        WHEN TIMESTAMPDIFF(YEAR, NGAYSINH, CURDATE()) BETWEEN 30 AND 39 THEN '30-39'
        WHEN TIMESTAMPDIFF(YEAR, NGAYSINH, CURDATE()) BETWEEN 40 AND 49 THEN '40-49'
        WHEN TIMESTAMPDIFF(YEAR, NGAYSINH, CURDATE()) BETWEEN 50 AND 59 THEN '50-59'
        ELSE '60+'
    END AS NHOMTUOI,
    COUNT(*) AS SOLUONG
FROM VIENCHUC
GROUP BY NHOMTUOI;

-- ? education information
CREATE VIEW VW_THONGKE_TRINHDOHOCVAN AS
