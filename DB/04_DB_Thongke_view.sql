    cm.TENCHUYENMON,
    COUNT(*) AS SOLUONG
FROM CO_TRDCM_CAONHAT ct
JOIN CHUYENMON cm
ON ct.MACHUYENMON = cm.MACHUYENMON
GROUP BY cm.TENCHUYENMON;

-- ? foreign language information
