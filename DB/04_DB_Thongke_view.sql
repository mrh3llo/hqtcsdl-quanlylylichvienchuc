    td.TRINHDONGHIEPVUCHUYENNGANH,
    COUNT(*) AS SOLUONG
FROM VIENCHUC vc
JOIN TRINHDOHOCVAN td
ON vc.MATRINHDO = td.MATRINHDO
GROUP BY td.TRINHDONGHIEPVUCHUYENNGANH;

-- specialized information
CREATE VIEW VW_THONGKE_CHUYENMON AS
