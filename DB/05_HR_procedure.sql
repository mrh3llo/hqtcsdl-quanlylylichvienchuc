CREATE PROCEDURE SP_CAPNHAT_USERS (
    IN p_mavienchuc CHAR(10),
    IN p_role VARCHAR(20)
)
BEGIN
    DECLARE old_role VARCHAR(20);
    DECLARE old_db_role VARCHAR(30);
    DECLARE new_db_role VARCHAR(30);

    SELECT ROLE INTO old_role FROM USERS WHERE MAVIENCHUC = p_mavienchuc;

    --  ? old role
    IF old_role = 'admin' THEN SET old_db_role = 'admin_role';
    ELSEIF old_role = 'hr' THEN SET old_db_role = 'hr_role';
    ELSEIF old_role = 'vienchuc' THEN SET old_db_role = 'vienchuc_role';
    ELSE SET old_db_role = 'thanhtra_role';
    END IF;

    -- ? new role
    IF p_role = 'admin' THEN SET new_db_role = 'admin_role';
    ELSEIF p_role = 'hr' THEN SET new_db_role = 'hr_role';
    ELSEIF p_role = 'vienchuc' THEN SET new_db_role = 'vienchuc_role';
    ELSE SET new_db_role = 'thanhtra_role';
    END IF;

    -- ? update system
    UPDATE USERS SET ROLE = p_role WHERE MAVIENCHUC = p_mavienchuc;


    IF old_db_role <> new_db_role THEN
        SET @sql_revoke = CONCAT("REVOKE '", old_db_role, "' FROM '", p_mavienchuc, "'@'%'");
        PREPARE stmt_rev FROM @sql_revoke; EXECUTE stmt_rev; DEALLOCATE PREPARE stmt_rev;

        SET @sql_grant = CONCAT("GRANT '", new_db_role, "' TO '", p_mavienchuc, "'@'%'");
        PREPARE stmt_gnt FROM @sql_grant; EXECUTE stmt_gnt; DEALLOCATE PREPARE stmt_gnt;

        SET @sql_def = CONCAT("SET DEFAULT ROLE '", new_db_role, "' TO '", p_mavienchuc, "'@'%'");
        PREPARE stmt_def FROM @sql_def; EXECUTE stmt_def; DEALLOCATE PREPARE stmt_def;
    END IF;
END$$
