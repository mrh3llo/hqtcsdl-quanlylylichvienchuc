    IF p_Category = 'suckhoe' THEN
        SET @sql = CONCAT(@sql, ', sk.TINHTRANGSUCKHOE AS TIEUCHI 
                    FROM VIENCHUC vc
                    JOIN CO_TINHTRANGSK ctsk ON vc.MAVIENCHUC = ctsk.MAVIENCHUC
